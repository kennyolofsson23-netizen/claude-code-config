"""Generate a machine-bootstrap script from the current setup.

Reads .claude.json for MCP servers and installed_plugins.json for plugins, and
emits a script that recreates both on another machine. Secret ENV VALUES ARE
NEVER EMITTED - only the variable names, so the script is safe to commit.
"""
import json
import os

HOME = os.path.expanduser("~")
CLAUDE_JSON = os.path.join(HOME, ".claude.json")
PLUGINS_JSON = os.path.join(HOME, ".claude", "plugins", "installed_plugins.json")
OUT = os.path.join(HOME, ".claude", "bootstrap-machine.sh")

SECRET_HINT = ("KEY", "TOKEN", "SECRET", "PASSWORD", "PASS", "CREDENTIAL", "AUTH", "PAT")


def load(p):
    try:
        with open(p, encoding="utf-8") as fh:
            return json.load(fh)
    except Exception:
        return {}


cfg = load(CLAUDE_JSON)
servers = cfg.get("mcpServers", {}) or {}
plugins = sorted((load(PLUGINS_JSON).get("plugins", {}) or {}).keys())

marketplaces = sorted({p.split("@", 1)[1] for p in plugins if "@" in p})

lines = []
add = lines.append
add("#!/usr/bin/env bash")
add("# bootstrap-machine.sh - recreate the machine-local half of the Claude setup.")
add("#")
add("# ~/.claude is version controlled (claude-code-config), but .gitignore")
add("# deliberately excludes plugins/, .claude.json and settings.json. So git")
add("# carries CLAUDE.md, rules, hooks, agents and skills - but NOT plugins,")
add("# MCP servers, or the settings.json that REGISTERS the hooks.")
add("#")
add("# Run this on a new machine AFTER cloning claude-code-config into ~/.claude.")
add("#")
add("# GENERATED by scripts/gen-bootstrap.py - re-run it after adding plugins or MCPs.")
add("set -uo pipefail")
add("")
add('echo "== marketplaces =="')
for m in marketplaces:
    if m in ("claude-plugins-official",):
        continue  # present by default
    add('claude plugin marketplace add "%s" || true' % m)
add("")
add('echo "== plugins (%d) =="' % len(plugins))
for p in plugins:
    add('claude plugin install "%s" || true' % p)
add("")
add('echo "== MCP servers (%d) =="' % len(servers))
add("# Secrets are NOT stored here. Export the named vars first, or let the")
add("# server prompt for OAuth on first use.")
add("")

needed = set()
for name in sorted(servers):
    s = servers[name] or {}
    typ = s.get("type") or ("http" if s.get("url") else "stdio")
    env = s.get("env") or {}
    for k, v in env.items():
        if any(h in k.upper() for h in SECRET_HINT):
            needed.add(k)

    if typ in ("http", "sse") and s.get("url"):
        flag = "--transport http" if typ == "http" else "--transport sse"
        add('claude mcp add %s "%s" "%s" || true' % (flag, name, s["url"]))
    else:
        cmd = s.get("command", "")
        args = " ".join('"%s"' % a for a in (s.get("args") or []))
        envflags = " ".join('--env %s="${%s:?set %s}"' % (k, k, k) for k in env)
        line = 'claude mcp add %s "%s" -- "%s" %s || true' % (envflags, name, cmd, args)
        add(" ".join(line.split()))

add("")
add('echo "== required env vars =="')
if needed:
    for k in sorted(needed):
        add('[ -n "${%s:-}" ] || echo "  MISSING: %s"' % (k, k))
else:
    add('echo "  none"')
add("")
add('echo "== manual steps git cannot carry =="')
add('cat <<\'EOF\'')
add("  1. settings.json is gitignored - it REGISTERS the hooks. Without it the")
add("     hook scripts exist but never fire. Copy it from the other machine.")
add("  2. Language servers: npm install -g typescript-language-server typescript pyright")
add("  3. Memory: clone claude-memory, then re-create the junctions")
add("     (~/.claude/projects/<slug>/memory -> ~/claude-memory/projects/<name>).")
add("  4. Secrets/.env files are not in git - copy them across separately.")
add("EOF")
add("")

with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")

print("wrote: %s" % OUT)
print("  plugins:     %d" % len(plugins))
print("  mcp servers: %d" % len(servers))
print("  secret vars referenced (names only): %s" % (", ".join(sorted(needed)) or "none"))
